"""Bundle optional Research Memory modules into Obsidian's single-file main.js.

Full ZIP/source installs also carry the modules for development. Official
three-file Obsidian installs must not depend on unshipped JavaScript files.
No third-party bundler, network or executable model output is involved.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]


def bundle_main() -> str:
    plugin = ROOT / "integrations/obsidian-paperflow-automation"
    paths = ["research.js", *[f"research-memory/{n}.js" for n in ("model", "storage", "client", "panel")]]
    definitions = ",\n".join(
        json.dumps("./" + name) + ": function(module, exports, require) {\n"
        + (plugin / name).read_text(encoding="utf-8") + "\n}"
        for name in paths
    )
    loader = '''
// Generated by scripts/bundle_research.py from audited local sources.
const __paperflowResearchRequire = (function(nativeRequire) {
  const definitions = {DEFINITIONS};
  const cache = new Map();
  function resolve(name, parent) {
    if (!name.startsWith('.')) return name;
    const parts = parent.split('/').slice(0, -1);
    for (const segment of name.split('/')) {
      if (!segment || segment === '.') continue;
      if (segment === '..') parts.pop(); else parts.push(segment);
    }
    return parts.join('/');
  }
  function load(name, parent) {
    const target = resolve(name, parent);
    if (!Object.prototype.hasOwnProperty.call(definitions, target)) return nativeRequire(target);
    if (cache.has(target)) return cache.get(target).exports;
    const module = {exports: {}}; cache.set(target, module);
    try { definitions[target](module, module.exports, child => load(child, target)); }
    catch (error) { cache.delete(target); throw error; }
    return module.exports;
  }
  return name => load(name, './main.js');
})(require);
'''.replace("DEFINITIONS", definitions)
    main = (plugin / "main.js").read_text(encoding="utf-8")
    anchor = 'require("./research.js").open(this)'
    if main.count(anchor) != 1:
        raise ValueError("Unexpected Research Memory entrypoint in main.js")
    return loader + main.replace(anchor, '__paperflowResearchRequire("./research.js").open(this)')


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(bundle_main(), encoding="utf-8")
